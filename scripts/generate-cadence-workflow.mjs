import fs from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { VALIDATION_SLOTS } from './lib/scan-admission.mjs';
export function finiteCadenceWorkflow(){
 let text=`# Generated by scripts/generate-cadence-workflow.mjs; manual finite validation only.
name: 有限两小时周期验证
on:
  workflow_dispatch:
  push:
    branches: [main]
    paths: [config/cadence-validation.json]
permissions:
  contents: read
  issues: write
  pages: write
  id-token: write
concurrency:
  group: price-guard-finite-cadence
  cancel-in-progress: false
jobs:
  anchor:
    runs-on: ubuntu-latest
    timeout-minutes: 3
    permissions:
      contents: read
    outputs:
      enabled: \${{ steps.anchor.outputs.enabled }}
      epoch: \${{ steps.anchor.outputs.epoch }}
      code_sha: \${{ steps.anchor.outputs.code_sha }}
    steps:
      - uses: actions/checkout@v4
      - uses: actions/setup-node@v4
        with:
          node-version: '20'
      - id: anchor
        run: node scripts/scan-admission.mjs anchor
        env:
          GITHUB_TOKEN: \${{ github.token }}
`;
 for(let i=0;i<VALIDATION_SLOTS;i++)text+=`  slot-${i}:
    if: \${{ !cancelled() && !failure() && needs.anchor.result == 'success' && needs.anchor.outputs.enabled == 'true'${i?` && needs.slot-${i-1}.result == 'success'`:''} }}
    needs: [anchor${i?`, slot-${i-1}`:''}]
    uses: ./.github/workflows/price-scan-transaction.yml
    secrets: inherit
    with:
      cadence_epoch: \${{ needs.anchor.outputs.epoch }}
      cadence_slot: '${i}'
      cadence_expected_sha: \${{ needs.anchor.outputs.code_sha }}
${i?`      cadence_previous_artifact: \${{ needs.slot-${i-1}.outputs.state_artifact }}\n`:''}  acceptance-${i}:
    needs: slot-${i}
    if: \${{ !cancelled() && needs.slot-${i}.result == 'success' && needs.slot-${i}.outputs.admitted == 'true' }}
    runs-on: ubuntu-latest
    timeout-minutes: 2
    permissions: {}
    steps:
      - name: 保留此槽实际产品验收结果
        env:
          COST_EXIT: \${{ needs.slot-${i}.outputs.cost_exit }}
          COVERAGE_EXIT: \${{ needs.slot-${i}.outputs.coverage_exit }}
        run: |
          echo "Cost acceptance exit: $COST_EXIT; complete-cycle acceptance exit: $COVERAGE_EXIT"
          test "$COST_EXIT" = 0 && test "$COVERAGE_EXIT" = 0
`;
 text+=`  window-acceptance:
    needs: [anchor, slot-0, slot-1, slot-2, slot-3, slot-4, slot-5]
    if: \${{ !cancelled() && needs.anchor.outputs.enabled == 'true' }}
    runs-on: ubuntu-latest
    timeout-minutes: 3
    permissions:
      contents: read
    steps:
      - uses: actions/checkout@v4
      - uses: actions/setup-node@v4
        with:
          node-version: '20'
      - run: node scripts/report-cadence-window.mjs
        env:
          CADENCE_NEEDS_JSON: \${{ toJSON(needs) }}
`;
 return text;
}
if(process.argv[1]===fileURLToPath(import.meta.url))await fs.writeFile(new URL('../.github/workflows/cadence-validation.yml',import.meta.url),finiteCadenceWorkflow());
